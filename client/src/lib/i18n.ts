/** Make `locale` available to t(). Resolves at once for Kiswahili. */
export function loadLocale(locale: Locale): Promise<void> {
  if (STRINGS[locale]) return Promise.resolve();
  if (locale !== 'en') return Promise.resolve();
  enLoading ??= import('./i18n.en').then((m) => { STRINGS.en = m.default; }).catch(() => { enLoading = null; });
  return enLoading;
}

export function isLocaleLoaded(locale: Locale): boolean {
  return !!STRINGS[locale];
}

function interpolate(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => vars[name] ?? match);
}

/**
 * Falls back to Kiswahili while English is still loading, rather than
 * showing a raw key — a screen must never look broken, especially one that
 * might be the SOS screen.
 */
export function t(locale: Locale, key: StringKey, vars?: Vars): string {
  const template = STRINGS[locale]?.[key] ?? SW[key] ?? key;
  return interpolate(template, vars);
}

